/** id → 主名字（同一 id 多个名字时取第一个），供日志/观测面回显。 */
export const FACE_NAMES = Object.freeze(
  Object.entries(FACES).reduce((acc, [name, id]) => {
    if (acc[id] === undefined) acc[id] = name;
    return acc;
  }, {}),
);

/** 表情总数，自测与观测面用。 */
export const FACE_COUNT = 321;

/**
 * 把一个用户输入（表情名或数字 id）解析成 OneBot face id。
 *
 * @param {} input 表情名（`"笑哭"`）或数字 id（`"182"` / `182`）。
 * @returns {{ ok: true, id: string, name: string, known: boolean }} 或
 *   `{ ok: false, error: string }`。
 */
export function resolveFaceId(input) {
  if (typeof input === 'number') {
    if (!Number.isInteger(input) || input < 0) {
      return { ok: false, error: `表情 id 必须是非负整数：${input}` };
    }
    return { ok: true, id: String(input), name: FACE_NAMES[input] ?? String(input), known: FACE_NAMES[input] !== undefined };
  }
  if (typeof input !== 'string') {
    return { ok: false, error: '表情必须是名字或数字 id' };
  }
  const text = input.trim();
  if (text === '') return { ok: false, error: '表情名不能为空' };

  const direct = FACES[text];
  if (direct !== undefined) return { ok: true, id: String(direct), name: text, known: true };

  // 纯数字：当 id 用（表里查不到也放行，模型可能知道表外的 id）
  if (/^\d+$/.test(text)) {
    const n = Number(text);
    return { ok: true, id: String(n), name: FACE_NAMES[n] ?? String(n), known: FACE_NAMES[n] !== undefined };
  }

  return { ok: false, error: `不认识的表情「${text}」——请用 QQ 里的表情名（如 笑哭、委屈、偷笑）或数字 id` };
}

/**
 * 拼一条「最接近的候选」提示，帮模型自我纠正。
 *
 * @param {} input 原始输入。
 * @param {number} [limit] 最多给几个候选。
 * @returns {string} 形如 `（你是不是想找：笑哭、大哭？）`；没有相近的就返回空串。
 */
export function suggestFaces(input, limit = 3) {
  if (typeof input !== 'string' || input.trim() === '') return '';
  const text = input.trim();
  const near = [];
  // 先收「包含关系」的候选（输入是名字的子串，或名字是输入的子串）
  for (const name of Object.keys(FACES)) {
    if (name.includes(text) || text.includes(name)) near.push(name);
    if (near.length >= limit) break;
  }
  if (near.length === 0) {
    // 退而求其次：共享任一字符
    const chars = new Set([...text]);
    for (const name of Object.keys(FACES)) {
      if ([...name].some((c) => chars.has(c))) near.push(name);
      if (near.length >= limit) break;
    }
  }
  return near.length === 0 ? '' : `（你是不是想找：${near.join('、')}？）`;
}
